// Stage 9E Phase E: builds evaluation-9e-tables.md from the stored result files (no engine needed).
//   node scripts/benchmarks/independent/report9e.mjs
// Inputs (all frozen result files; nothing is re-run here):
//   run2b  pre-fix engine, final scorer           (the frozen "original predictions" of the 9D benchmark)
//   run4   Stage 9D final engine                  (what 9D reported)
//   run5   Stage 9E engine                        (this stage)
//   heldout-9e-*  the untouched HX set on the 9D engine, the 9E engine, and after the HX-03 fix
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CASES } from "./cases.mjs";
import { CASES as HX_CASES } from "./cases9e.mjs";
import { CASES as ADDENDA } from "./cases9e-addenda.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const load = (name) => JSON.parse(fs.readFileSync(path.join(here, "results", name), "utf8"));
const run2b = load("independent-results-run2b-pre-fix-engine-final-scorer.json");
const run4 = load("independent-results-run4-final.json");
const run5 = load("independent-results-run5-stage9e.json");
const audit = load("provenance-audit.json");
const hx9d = load("heldout-9e-baseline-9d-engine.json");
const hx9e = load("heldout-9e-stage9e-engine.json");
const hxFix = load("heldout-9e-after-hx03-fix.json");
const addenda = load("addenda-9e.json");

const byId = (data) => Object.fromEntries(data.records.map((r) => [r.id, r]));
const [r2b, r4, r5] = [byId(run2b), byId(run4), byId(run5)];
const caseById = Object.fromEntries(CASES.map((c) => [c.id, c]));
const categoryOf = Object.fromEntries(audit.rows.map((r) => [r.id, r.category]));
const DIMENSIONS = ["structure", "connectivity", "regiochemistry", "stereochemistry", "classification", "conditions", "ambiguity", "unsupported", "routeDiscovery", "routeVerification", "routePlausibility", "workspace"];

const tally = (ids, data, dimension) => {
  const counts = {};
  for (const id of ids) {
    const verdict = data[id]?.dimensions[dimension];
    if (!verdict || verdict.status === "n/a") continue;
    counts[verdict.status] = (counts[verdict.status] ?? 0) + 1;
  }
  return Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ");
};
const outputs = (record) => (record?.engine?.outcomes ?? []).map((o) => `${o.product}${o.class && o.class !== "unranked" && o.class !== "single-outcome" ? ` [${o.class}]` : o.class === "unranked" ? " [unranked]" : ""}`).join("<br>") || "(none)";
const outputKey = (record) => JSON.stringify((record?.engine?.outcomes ?? []).map((o) => [o.product, o.class]));

const lines = ["# Stage 9E: independent evaluation tables", "", "Generated by `report9e.mjs` from stored result files. Verdicts are never combined into one accuracy number.", ""];

// ---- 1. provenance
const groups = audit.summary;
lines.push("## 1. Which cases may count as independently validated", "", "| category (Phase A audit) | n | cases |", "|---|---|---|");
for (const [category, ids] of Object.entries(groups)) lines.push(`| ${category} | ${ids.length} | ${ids.join(", ")} |`);
lines.push("", `The 9D report's headline set had ${audit.looseOriginal.length} cases; after the source, overlap and development-influence audit the strictly independent held-out set is **${audit.strict.length}**.`, "");

// ---- 2. dimension tallies by set
const sets = [
  ["Strictly independent held-out (frozen cases)", audit.strict],
  ["Original 9D headline set", audit.looseOriginal],
  ["Verified but development-informed or development-guided", [...(groups["verified-development-informed"] ?? []), ...(groups["development-guided"] ?? [])]],
  ["Provisional (never quoted as validated)", groups.provisional ?? []],
  ["All 57 frozen cases", CASES.map((c) => c.id)],
];
lines.push("## 2. Pre-fix engine, Stage 9D engine and Stage 9E engine on the frozen benchmark", "", "Pre-fix = the frozen original predictions (run 2b). Stage 9D = what 9D reported (run 4). Stage 9E = this stage (run 5).", "");
for (const [title, ids] of sets) {
  lines.push(`### ${title} (${ids.length} cases)`, "", "| dimension | pre-fix (frozen) | Stage 9D | Stage 9E |", "|---|---|---|---|");
  for (const dimension of DIMENSIONS) {
    const [a, b, c] = [tally(ids, r2b, dimension), tally(ids, r4, dimension), tally(ids, r5, dimension)];
    if (a || b || c) lines.push(`| ${dimension} | ${a || "-"} | ${b || "-"} | ${c || "-"} |`);
  }
  lines.push("");
}

// ---- 3. change table
lines.push("## 3. Every case whose predicted output or verdict changed between Stage 9D and Stage 9E", "", "`held-out status` is the Phase A category. A change in a case that is not `independent-held-out` is development evidence, not validation.", "");
lines.push("| id | held-out status | original prediction (9D) | updated prediction (9E) | expected | reference | verdict change |", "|---|---|---|---|---|---|---|");
let changed = 0;
for (const record of run5.records) {
  const before = r4[record.id];
  const verdictChanges = DIMENSIONS.filter((d) => before?.dimensions[d]?.status !== record.dimensions[d]?.status && record.dimensions[d]?.status !== "n/a").map((d) => `${d}: ${before?.dimensions[d]?.status ?? "n/a"} → ${record.dimensions[d].status}`);
  if (outputKey(before) === outputKey(record) && verdictChanges.length === 0) continue;
  changed += 1;
  const c = caseById[record.id];
  const expected = (c?.expect?.products ?? []).map((p) => `${p.smiles} (${p.role})`).join("<br>") || (c?.target ?? "-");
  const forbidden = (c?.expect?.forbidden ?? []).length ? `<br>not: ${c.expect.forbidden.join(", ")}` : "";
  lines.push(`| ${record.id} | ${categoryOf[record.id]} | ${outputs(before)} | ${outputs(record)} | ${expected}${forbidden} | ${(c?.provenance?.sources ?? []).join(", ") || "none"} | ${verdictChanges.join("; ") || "output changed, verdict same"} |`);
}
lines.push("", `${changed} of ${run5.records.length} frozen cases changed.`, "");

// ---- 4. untouched set
lines.push("## 4. The untouched evaluation set (HX-01..HX-11)", "", "Written after the 9E engine work and before it was run; frozen in commit `8150887`. Reaction classes whose rules were not modified in Stage 9E, except that HX-03 exposed a real defect that was then fixed (so HX-03 is development-guided after the fix).", "");
lines.push("| id | expected | Stage 9D engine | Stage 9E engine, first run | after the HX-03 fix | note |", "|---|---|---|---|---|---|");
const hx = (data) => byId(data);
const [h9d, h9e, hfix] = [hx(hx9d), hx(hx9e), hx(hxFix)];
const verdict = (record) => ["connectivity", "regiochemistry", "stereochemistry", "classification"].filter((d) => record.dimensions[d]?.status && record.dimensions[d].status !== "n/a").map((d) => `${d}: ${record.dimensions[d].status}`).join("; ");
const notes = {
  "HX-03": "genuine defect: the HX rule attacked the more substituted carbon for primary/secondary epoxide carbons, contradicting both cited pages; fixed; development-guided afterwards",
  "HX-06": "authoring error (the E2 base is a reagent supplied by the rule, so ethoxide is an invalid second molecule); NOT edited; restated as HX-06R; overlaps a 9E fixture so excluded from held-out figures",
  "HX-11": "stereochemistry 'incomplete': the engine leaves the cis relative configuration unspecified at workspace level",
  "HX-02": "classification abstained: the engine does not rank the two regioisomers",
};
for (const c of HX_CASES) {
  const expected = (c.expect.products ?? []).map((p) => `${p.smiles} (${p.role})`).join("<br>");
  lines.push(`| ${c.id} | ${expected} | ${verdict(h9d[c.id])} | ${verdict(h9e[c.id])} | ${verdict(hfix[c.id])} | ${notes[c.id] ?? ""} |`);
}
const heldOutIds = HX_CASES.map((c) => c.id).filter((id) => id !== "HX-06" && id !== "HX-03");
lines.push("", `Genuinely untouched and independent (HX-03 and HX-06 excluded): **${heldOutIds.length} cases**.`, "", "| dimension | Stage 9D engine | Stage 9E engine |", "|---|---|---|");
for (const dimension of ["structure", "connectivity", "regiochemistry", "stereochemistry", "classification"]) {
  const [a, b] = [tally(heldOutIds, h9d, dimension), tally(heldOutIds, h9e, dimension)];
  if (a || b) lines.push(`| ${dimension} | ${a || "-"} | ${b || "-"} |`);
}
lines.push("", "Addendum (not counted): " + ADDENDA.map((c) => `${c.id} ${verdict(byId(addenda)[c.id])}`).join("; "), "");

// ---- 5. runtime
const runtime = (data) => data.summary?.runtime ?? {};
lines.push("## 5. Runtime and memory", "", "| run | total ms | slowest case ms | peak RSS MB |", "|---|---|---|---|");
for (const [name, data] of [["Stage 9D (run 4)", run4], ["Stage 9E (run 5)", run5]]) {
  const rt = runtime(data);
  lines.push(`| ${name} | ${rt.totalMs ?? "?"} | ${rt.slowestMs ?? "?"} | ${rt.peakRssMB ?? "?"} |`);
}
lines.push("", "Same-machine route-search timings measured in this stage with the 9D engine in a separate worktree: RT-01 3.4-4.0 s, RT-02 2.3-2.5 s, RT-03 4.6-4.9 s (9D engine); 3.5, 2.3 and 3.9-4.1 s (9E engine). The faster figures quoted in the 9D report came from a quieter machine.", "");

fs.writeFileSync(path.join(here, "evaluation-9e-tables.md"), lines.join("\n"));
console.log(`wrote evaluation-9e-tables.md (${changed} changed cases)`);
